#!/usr/bin/env node
/**
 * Rewrites the generated part of compatibility.html from the extension repo's
 * COMPATIBILITY.md. No part of that region is maintained by hand: edit the
 * Markdown upstream, and this script, run daily by refresh-status.yml, brings
 * the page along.
 *
 * Unlike roadmap.html, this is a rendering rather than a rewrite. Every mark and
 * every note on the page is a cell or a paragraph of the Markdown, so nothing here
 * needs a person's judgment, and a page that lags the file by a day is the worst
 * case.
 *
 * The Markdown is held to a shape, and the script refuses to write when it does
 * not find it: a half-parsed table on a live page is worse than yesterday's.
 *
 *   ## Desktop | Android | iOS
 *   | Browser | Engine | Install | Bookmarks | ... | WebDAV |   one row per browser
 *   ### <platform>: notes
 *   #### <browser>                                             one per table row
 *   **Install from:** <route>
 *   <paragraphs>
 *
 *   node scripts/sync-compat.mjs                    read upstream main, rewrite the page
 *   node scripts/sync-compat.mjs --from <file>      read a local COMPATIBILITY.md instead
 *   node scripts/sync-compat.mjs --check            exit 1 if the page is out of date
 */
import { readFile, writeFile } from "node:fs/promises";

const root = new URL("../", import.meta.url);
const PAGE_FILE = new URL("compatibility.html", root);
const RAW = "https://raw.githubusercontent.com/konabe-studio/konode/main/COMPATIBILITY.md";
const REPO_BLOB = "https://github.com/konabe-studio/konode/blob/main/";
const START = "<!-- compat:start: generated by scripts/sync-compat.mjs from COMPATIBILITY.md; edit that, not this -->";
const END = "<!-- compat:end -->";

const PLATFORMS = ["Desktop", "Android", "iOS"];
const MATRIX_HEAD = ["Browser", "Engine", "Install", "Bookmarks", "Open tabs", "History", "Extensions", "Drive", "GitHub", "WebDAV"];
/** Shown above the columns. The Markdown says "Drive" to stay narrow; the page has room. */
const COLUMN_LABEL = { Drive: "Google Drive", Extensions: "Extension list" };

const MARKS = {
  "✅": ["ok", "Works"],
  "⚠": ["lim", "Works with a limitation"],
  "❌": ["no", "Does not work"],
  "🚫": ["na", "Not possible on this browser"],
  "⏳": ["tbd", "Not tested yet"],
};
/** 16px line icons, stroked in currentColor by docs.css. */
const ICONS = {
  ok: '<path d="M4 8.5l2.5 2.5L12 5.5"/>',
  lim: '<path d="M8 4.5v4"/><path d="M8 11.5v.01"/>',
  no: '<path d="M5 5l6 6M11 5l-6 6"/>',
  na: '<circle cx="8" cy="8" r="5"/><path d="M4.5 11.5l7-7"/>',
  tbd: '<path d="M5.5 8h5"/>',
};

const args = process.argv.slice(2);
const check = args.includes("--check");
const fromAt = args.indexOf("--from");
const from = fromAt >= 0 ? args[fromAt + 1] : null;

function fail(why) {
  console.error(`sync-compat: ${why}. Nothing was written.`);
  process.exit(2);
}

// ── Markdown, as far as COMPATIBILITY.md uses it ─────────────────────────────

const escapeHtml = (s) => s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");
const markOf = (cell) => MARKS[cell.replace(/️/g, "").trim()];
const slug = (s) => s.toLowerCase().replace(/\([^)]*\)/g, "").replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");

/** Links, `code` and **bold**. A link into the repo goes to the file on GitHub. */
function inline(text) {
  return text.split("`").map((part, i) => {
    if (i % 2 === 1) return `<code>${escapeHtml(part)}</code>`;
    let s = escapeHtml(part);
    s = s.replace(/\[([^\]]+)\]\(([^)\s]+)\)/g, (_, label, url) => {
      const href = /^https?:\/\//.test(url) ? url : REPO_BLOB + url;
      return `<a href="${href}">${label}</a>`;
    });
    return s.replace(/\*\*([^*]+)\*\*/g, "<strong>$1</strong>");
  }).join("");
}

const cellsOf = (line) => line.trim().replace(/^\|/, "").replace(/\|$/, "").split("|").map((c) => c.trim());

/** The document as a list of blocks: h1-h4, paragraphs, tables and ordered lists. */
function blocks(md) {
  const lines = md.replace(/\r\n/g, "\n").split("\n");
  const out = [];
  for (let i = 0; i < lines.length;) {
    const line = lines[i];
    if (!line.trim()) { i++; continue; }
    const h = line.match(/^(#{1,4}) (.+)$/);
    if (h) { out.push({ type: `h${h[1].length}`, text: h[2].trim() }); i++; continue; }
    if (line.startsWith("|")) {
      const rows = [];
      while (i < lines.length && lines[i].startsWith("|")) rows.push(lines[i++]);
      if (rows.length < 2 || !/^\|[\s|:-]+\|$/.test(rows[1].trim())) fail(`a table without a separator row near "${rows[0].slice(0, 60)}"`);
      out.push({ type: "table", head: cellsOf(rows[0]), rows: rows.slice(2).map(cellsOf) });
      continue;
    }
    if (/^\d+\. /.test(line)) {
      const items = [];
      while (i < lines.length && (/^\d+\. /.test(lines[i]) || /^ {2,}\S/.test(lines[i]))) {
        if (/^\d+\. /.test(lines[i])) items.push(lines[i].replace(/^\d+\. /, ""));
        else items[items.length - 1] += ` ${lines[i].trim()}`;
        i++;
      }
      out.push({ type: "ol", items });
      continue;
    }
    const para = [];
    while (i < lines.length && lines[i].trim() && !/^(#{1,4} |\||\d+\. )/.test(lines[i])) para.push(lines[i++].trim());
    out.push({ type: "p", text: para.join(" ") });
  }
  return out;
}

// ── Rendering ────────────────────────────────────────────────────────────────

const mark = ([kind, label]) =>
  `<span class="mk mk-${kind}" title="${label}"><svg viewBox="0 0 16 16" aria-hidden="true" focusable="false">${ICONS[kind]}</svg><span class="vh">${label}</span></span>`;

function legend(table) {
  const items = table.rows.map(([cell, meaning]) => {
    const m = markOf(cell);
    if (!m) fail(`a legend row without a known mark: "${cell}"`);
    return `      <li>${mark(m)} ${inline(meaning)}</li>`;
  });
  return `    <ul class="mk-legend">\n${items.join("\n")}\n    </ul>`;
}

function matrix(platform, table, notesById) {
  if (table.head.join("|") !== MATRIX_HEAD.join("|")) fail(`the ${platform} table's columns are not ${MATRIX_HEAD.join(", ")}`);
  const cols = MATRIX_HEAD.slice(2);
  const head = cols.map((c) => `<th scope="col">${COLUMN_LABEL[c] ?? c}</th>`).join("");
  const rows = table.rows.map((cells) => {
    if (cells.length !== MATRIX_HEAD.length) fail(`a ${platform} row with ${cells.length} cells: "${cells[0]}"`);
    const [name, engine, ...marks] = cells;
    const id = `${slug(platform)}-${slug(name)}`;
    const note = notesById.get(id);
    if (!note) fail(`the ${platform} row "${name}" has no "#### ${name}" note`);
    note.used = true;
    const th = `<th scope="row"><a href="#${id}">${inline(name)}</a><span class="eng">${inline(engine)}</span></th>`;
    // A row stops at the first blank cell: Konode cannot be installed there.
    const stop = marks.findIndex((c) => c === "");
    const shown = stop < 0 ? marks : marks.slice(0, stop);
    const tds = shown.map((c) => {
      const m = markOf(c);
      if (!m) fail(`an unknown mark "${c}" in the ${platform} row "${name}"`);
      return `<td>${mark(m)}</td>`;
    });
    if (stop >= 0) {
      if (marks.slice(stop).some((c) => c !== "")) fail(`a mark after a blank cell in the ${platform} row "${name}"`);
      const why = note.paras[0] && note.paras[0].length <= 90 ? inline(note.paras[0]) : "Konode cannot be installed here";
      tds.push(`<td class="stop" colspan="${marks.length - stop}">${why}</td>`);
    }
    return `          <tr>${th}${tds.join("")}</tr>`;
  });
  return [
    `    <div class="compat-scroll" role="region" aria-label="${platform} browsers" tabindex="0">`,
    `      <table class="compat">`,
    `        <thead><tr><th scope="col">Browser</th>${head}</tr></thead>`,
    `        <tbody>`,
    ...rows,
    `        </tbody>`,
    `      </table>`,
    `    </div>`,
  ].join("\n");
}

/** "#### Name" blocks under "### <platform>: notes", keyed the way the table links them. */
function notesOf(platform, list) {
  const notes = new Map();
  for (let i = 0; i < list.length; i++) {
    if (list[i].type !== "h4") fail(`something other than a "#### browser" note under "### ${platform}: notes"`);
    const name = list[i].text;
    const route = list[i + 1];
    const m = route?.type === "p" && route.text.match(/^\*\*Install from:\*\* (.+)$/);
    if (!m) fail(`the note "${name}" does not start with "**Install from:**"`);
    const paras = [];
    let j = i + 2;
    while (j < list.length && list[j].type === "p") paras.push(list[j++].text);
    notes.set(`${slug(platform)}-${slug(name)}`, { name, route: m[1], paras, used: false });
    i = j - 1;
  }
  return notes;
}

function notesHtml(platform, notes, engines) {
  const items = [...notes.entries()].map(([id, n]) => [
    `      <section class="cn-item" id="${id}" aria-labelledby="${id}-h">`,
    `        <div class="cn-head">`,
    `          <h3 id="${id}-h">${inline(n.name)}</h3>`,
    `          <p class="eng">${inline(engines.get(id) ?? "")}</p>`,
    `        </div>`,
    `        <div class="cn-body">`,
    `          <p class="cn-route"><span>Install from</span> ${n.route === "nowhere" ? "Nowhere: no extension support" : inline(n.route)}</p>`,
    ...n.paras.map((p) => `          <p>${inline(p)}</p>`),
    `        </div>`,
    `      </section>`,
  ].join("\n"));
  return `    <div class="cn">\n${items.join("\n")}\n    </div>`;
}

function textTable(table) {
  const cell = (c) => { const m = markOf(c); return m ? mark(m) : inline(c); };
  const head = table.head.map((c, i) => (i === 0 && !c ? `<td></td>` : `<th scope="col">${inline(c)}</th>`)).join("");
  const rows = table.rows.map(([first, ...rest]) => `          <tr><th scope="row">${inline(first)}</th>${rest.map((c) => `<td>${cell(c)}</td>`).join("")}</tr>`);
  return [
    `    <div class="compat-scroll" role="region" aria-label="What differs by engine" tabindex="0">`,
    `      <table class="compat compat-text">`,
    `        <thead><tr>${head}</tr></thead>`,
    `        <tbody>`,
    ...rows,
    `        </tbody>`,
    `      </table>`,
    `    </div>`,
  ].join("\n");
}

const SECTION_ID = { Desktop: "desktop", Android: "android", iOS: "ios", "What differs by engine": "engines", "Test checklist (per browser)": "checklist", "Reporting a browser": "report" };

function render(md) {
  const all = blocks(md);
  if (all[0]?.type !== "h1") fail("the file does not start with its title");
  const sections = [];
  let current = { title: null, body: [] };
  for (const b of all.slice(1)) {
    if (b.type === "h2") { sections.push(current); current = { title: b.text, body: [] }; } else current.body.push(b);
  }
  sections.push(current);

  const out = [];
  const intro = sections.shift();
  for (const b of intro.body) {
    if (b.type !== "p") fail("the introduction holds something other than paragraphs");
    const cls = /^Last updated:/.test(b.text) ? "updated" : "lead";
    out.push(`    <p class="${cls}">${inline(b.text)}</p>`);
  }

  const toc = sections.filter((s) => s.title !== "Legend").map((s) => {
    const id = SECTION_ID[s.title];
    if (!id) fail(`an unknown section "## ${s.title}"`);
    return `        <li><a href="#${id}">${inline(s.title)}</a></li>`;
  });
  out.push(`    <nav class="toc" aria-label="On this page">\n      <h2>On this page</h2>\n      <ol>\n${toc.join("\n")}\n      </ol>\n    </nav>`);

  for (const s of sections) {
    if (s.title === "Legend") {
      const t = s.body.find((b) => b.type === "table");
      if (!t) fail("the legend has no table");
      out.push(`    <div class="mk-key" aria-label="What the marks mean">`);
      out.push(legend(t));
      for (const b of s.body.filter((b) => b.type === "p")) out.push(`      <p>${inline(b.text)}</p>`);
      out.push(`    </div>`);
      continue;
    }
    const id = SECTION_ID[s.title];
    out.push(`\n    <h2 id="${id}">${inline(s.title)}</h2>`);
    if (PLATFORMS.includes(s.title)) {
      const at = s.body.findIndex((b) => b.type === "h3");
      if (at < 0 || s.body[at].text !== `${s.title}: notes`) fail(`"## ${s.title}" has no "### ${s.title}: notes"`);
      const before = s.body.slice(0, at);
      const table = before.find((b) => b.type === "table");
      if (!table) fail(`"## ${s.title}" has no table`);
      for (const b of before.filter((b) => b.type === "p")) out.push(`    <p>${inline(b.text)}</p>`);
      const notes = notesOf(s.title, s.body.slice(at + 1));
      const engines = new Map(table.rows.map((r) => [`${slug(s.title)}-${slug(r[0])}`, r[1]]));
      out.push({ wide: matrix(s.title, table, notes) });
      const orphan = [...notes.values()].find((n) => !n.used);
      if (orphan) fail(`the ${s.title} note "${orphan.name}" has no row in the table`);
      out.push(`    <h3 class="cn-title">Notes, browser by browser</h3>`);
      out.push(notesHtml(s.title, notes, engines));
      continue;
    }
    for (const b of s.body) {
      if (b.type === "p") out.push(`    <p>${inline(b.text)}</p>`);
      else if (b.type === "table") out.push({ wide: textTable(b) });
      else if (b.type === "ol") out.push(`    <ol class="steps">\n${b.items.map((it) => `      <li>${inline(it)}</li>`).join("\n")}\n    </ol>`);
      else fail(`an unexpected ${b.type} under "## ${s.title}"`);
    }
  }

  // Text runs share a column at the prose measure, and the tables between them run wide.
  // One wrapper per run rather than a max-width on each child: a max-width in ch follows
  // the element's own font, and a heading measured in its own ch is wider than the page.
  const html = [];
  let open = false;
  for (const piece of out) {
    const wide = typeof piece !== "string";
    if (wide && open) { html.push(`    </div>`); open = false; }
    if (!wide && !open) { html.push(`    <div class="col">`); open = true; }
    html.push(wide ? piece.wide : piece);
  }
  if (open) html.push(`    </div>`);
  return html.join("\n");
}

// ── The page ─────────────────────────────────────────────────────────────────

const md = from ? await readFile(from, "utf8") : await (async () => {
  const res = await fetch(RAW, { headers: { "user-agent": "konode-site compatibility sync" } });
  if (!res.ok) fail(`${RAW} answered ${res.status}`);
  return res.text();
})();
const generated = render(md);
if (/—/.test(generated)) fail("the rendering carries an em dash, which the site does not use");

const page = (await readFile(PAGE_FILE, "utf8")).replace(/\r\n/g, "\n");
const a = page.indexOf(START), b = page.indexOf(END);
if (a < 0 || b < a) fail("compatibility.html has no compat:start / compat:end markers");
const next = `${page.slice(0, a + START.length)}\n${generated}\n    ${page.slice(b)}`;

if (check) {
  if (next !== page) { console.log("compatibility.html is out of date."); process.exit(1); }
  console.log("compatibility.html is up to date.");
} else if (next !== page) {
  await writeFile(PAGE_FILE, next);
  console.log("compatibility.html rewritten.");
} else {
  console.log("compatibility.html already matches.");
}
